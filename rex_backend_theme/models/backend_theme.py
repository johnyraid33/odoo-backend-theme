HEADER = "// Generated by Settings > Backend Theme. See the module's user_variables.scss.\n"


def render_user_variables(values):
    """The SCSS variables for validated values, accent variants included."""
    variants = accent_variants(values['accent'], NEUTRAL_SCALES[values['neutral']])
    lines = [
        ('accent', values['accent']),
        ('neutral', values['neutral']),
        ('radius', values['radius']),
        ('primary', variants['primary']),
        ('primary-foreground', variants['primary_foreground']),
        ('primary-text', variants['primary_text']),
        ('primary-text-dark', variants['primary_text_dark']),
    ]
    return ''.join('$rx-user-%s: %s;\n' % line for line in lines)


class RexBackendTheme(models.AbstractModel):
    """Stores the theme values chosen in the settings into the asset bundles."""

    _name = 'rex.backend.theme'
    _description = 'Rex Backend Theme'

    @api.model
    def _validate(self, values):
        values = {**DEFAULTS, **{k: v for k, v in values.items() if v}}
        values['accent'] = values['accent'].lower()
        if not ACCENT_RE.match(values['accent']):
            raise ValidationError(self.env._('The accent colour must be a hex colour such as #6366f1.'))
        if values['neutral'] not in dict(NEUTRALS):
            raise ValidationError(self.env._('Unknown neutral palette: %s', values['neutral']))
        if values['radius'] not in dict(RADII):
            raise ValidationError(self.env._('Unknown corner radius: %s', values['radius']))
        return values

    @api.model
    def _custom_url(self, bundle):
        return '/_custom/%s%s' % (bundle, USER_VARIABLES)

    @api.model
    def _save_user_variables(self, values):
        """Write the values into the bundles; the defaults remove the customisation."""
        values = self._validate(values)
        if values == DEFAULTS:
            self._reset_user_variables()
            return
        raw = (HEADER + render_user_variables(values)).encode()
        Attachment = self.env['ir.attachment'].sudo()
        Asset = self.env['ir.asset'].sudo().with_context(active_test=False)
        for bundle in BUNDLES:
            url = self._custom_url(bundle)
            attachment = Attachment.search([('url', '=', url), ('type', '=', 'binary')], limit=1)
            if attachment:
                attachment.raw = raw
            else:
                Attachment.create({
                    'name': 'user_variables.scss',
                    'type': 'binary',
                    'mimetype': 'text/scss',
                    'raw': raw,
                    'url': url,
                })
            if not Asset.search([('path', '=', url)], limit=1):
                Asset.create({
                    'name': 'Rex Backend Theme: settings (%s)' % bundle,
                    'bundle': bundle,
                    'directive': 'replace',
                    'target': USER_VARIABLES,
                    'path': url,
                })
        self.env.registry.clear_cache('assets')

    @api.model
    def _refresh_user_variables(self):
        """Rewrite a customisation with the current derivation (module update)."""
        if not self.env['ir.asset'].sudo().with_context(active_test=False).search_count(
                [('target', '=', USER_VARIABLES)], limit=1):
            return
        get = self.env['ir.config_parameter'].sudo().get_param
        self._save_user_variables({key: get('rex_backend_theme.%s' % key) for key in DEFAULTS})

    @api.model
    def _reset_user_variables(self):
        urls = [self._custom_url(bundle) for bundle in BUNDLES]
        self.env['ir.asset'].sudo().with_context(active_test=False).search([('path', 'in', urls)]).unlink()
        self.env['ir.attachment'].sudo().search([('url', 'in', urls), ('type', '=', 'binary')]).unlink()
        self.env.registry.clear_cache('assets')
