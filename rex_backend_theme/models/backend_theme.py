import re

from odoo import api, models
from odoo.exceptions import ValidationError

from .colors import accent_variants

USER_VARIABLES = '/rex_backend_theme/static/src/scss/user_variables.scss'
# Every bundle that compiles the tokens. The dark bundles include the first
# two, so the replacement applies to them as well; the frontend bundle styles
# the login page.
BUNDLES = ('web.assets_backend', 'web.assets_backend_lazy', 'web.assets_frontend')

ACCENT_RE = re.compile(r'^#[0-9a-fA-F]{6}$')
NEUTRALS = [
    ('zinc', 'Zinc'),
    ('slate', 'Slate'),
    ('stone', 'Stone'),
    ('neutral', 'Gray'),
]
RADII = [
    ('none', 'Square'),
    ('sm', 'Small'),
    ('md', 'Medium'),
    ('lg', 'Large'),
]
DEFAULTS = {'accent': '#6366f1', 'neutral': 'zinc', 'radius': 'md'}

# Runtime values: applied by the web client, no recompilation.
DENSITIES = [
    ('comfortable', 'Comfortable'),
    ('compact', 'Compact'),
]
DEFAULT_DENSITY = 'comfortable'
SCHEMES = [('light', 'Light'), ('dark', 'Dark'), ('system', 'System')]
SIDEBAR_MODES = [('expanded', 'Expanded'), ('rail', 'Icons only')]

# Same palettes as $rx-neutrals in static/src/scss/tokens.scss (a test
