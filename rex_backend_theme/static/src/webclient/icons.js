export function iconFor(menu) {
    if (menu.xmlid && BY_XMLID[menu.xmlid]) {
        return BY_XMLID[menu.xmlid];
    }
    const key = `${menu.xmlid || ""} ${menu.name || ""}`.toLowerCase();
    const found = BY_PATTERN.find(([re]) => re.test(key));
    return found ? found[1] : "article";
}

